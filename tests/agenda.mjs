import './datiDiProva.mjs';
import assert from 'node:assert/strict';
import { state } from '../dist/js/services/store.js?v=65';
import { clearAgenda, saveEntry, saveLog, saveGoal, deleteAgenda, saveWorkWeek } from '../dist/js/services/agendaService.js?v=65';
import { weekStart, summary, dayEntries, toInstant, minutesBetween, goalProgress } from '../dist/js/utils/agenda.js?v=65';
import { initialWeek, seminaSettimana } from './datiDiProva.mjs';
const storage = new Map(); globalThis.localStorage = { getItem: k => storage.get(k), setItem: (k,v) => storage.set(k,v) };
state.mode = 'demo'; clearAgenda();
assert.equal(weekStart('2026-10-11'), '2026-10-05');
assert.equal(weekStart('2026-10-12'), '2026-10-12');
await seminaSettimana();
assert.equal(state.scheduleEntries.filter(e => e.kind === 'shift').length, 4);
const data = summary(state.scheduleEntries, state.timeLogs, '2026-10-05', '2026-10-11', state.timezone);
assert.equal(data.byCategory.work.planned, 1920); assert.equal(data.byCategory.study.planned, 480); assert.equal(data.actual, 0);
const night = state.scheduleEntries.find(e => e.entry_date === '2026-10-08' && e.kind === 'shift');
assert.equal(night.planned_minutes, 480);
assert.equal(summary([night], [], '2026-10-08', '2026-10-08', state.timezone).planned, 30);
assert.equal(summary([night], [], '2026-10-09', '2026-10-09', state.timezone).planned, 450);
assert(dayEntries([night], '2026-10-09', state.timezone).includes(night));
await assert.rejects(() => seminaSettimana());
const entry = await saveEntry({ title:'Study test',category:'study',entry_date:'2026-10-11',planned_minutes:120 });
const log = await saveLog({ entry_id: entry.id, started_at: toInstant('2026-10-11T23:00'), ended_at: toInstant('2026-10-12T01:00') });
assert.equal(summary([entry], state.timeLogs, '2026-10-05', '2026-10-11', state.timezone).actual, 60);
assert.equal(summary([entry], state.timeLogs, '2026-10-12', '2026-10-18', state.timezone).actual, 60);
await assert.rejects(() => saveLog({entry_id:night.id,started_at:toInstant('2026-10-11T23:30'),ended_at:toInstant('2026-10-12T00:00')}));
const edited = await saveLog({entry_id:entry.id,started_at:toInstant('2026-10-11T22:00'),ended_at:toInstant('2026-10-11T23:00')}, log);
assert.equal(summary([entry], state.timeLogs, '2026-10-11', '2026-10-11', state.timezone).actual, 60);
await saveEntry({...entry,is_completed:true},entry);
const goal = await saveGoal({title:'Studio',category:'study',week_start:'2026-10-05',unit:'minutes',target:480,stretch_target:480});
assert.equal(goalProgress(goal,[entry],state.timeLogs,state.timezone),60);
const backlog = await saveEntry({title:'No date',category:'personal',planned_minutes:90});
assert.equal(summary([backlog],[], '2026-10-05','2026-10-11',state.timezone).planned,0);
await assert.rejects(()=>saveEntry({...backlog,is_completed:true},backlog));
await assert.rejects(()=>saveEntry({title:'Bad',category:'study',entry_date:'2026-02-30'}));
await assert.rejects(()=>saveEntry({title:'Bad',category:'study',planned_minutes:-1}));
await assert.rejects(()=>saveGoal({title:'Bad',category:'study',week_start:'2026-10-06',unit:'minutes',target:480}));
assert.equal(minutesBetween(toInstant('2026-10-25T00:00'),toInstant('2026-10-25T06:00')),420);
assert.throws(()=>toInstant('2026-03-29T02:30'));
assert.equal(toInstant('2026-10-25T02:30'),'2026-10-25T00:30:00.000Z');
await saveWorkWeek('2026-10-12', Array.from({length:7},(_,i)=>i===0 ? {kind:'shift',from:'23:30',to:'07:30'} : {kind:'off'}));
assert.equal(state.scheduleEntries.filter(e=>e.entry_date==='2026-10-12')[0].planned_minutes,480);
const snapshot=JSON.stringify(state.scheduleEntries);
await assert.rejects(()=>saveWorkWeek('2026-10-12',[{kind:'shift',from:'07:30',to:''}]));
assert.equal(JSON.stringify(state.scheduleEntries),snapshot);
storage.set('cm-local-demo','yes');
await saveEntry({...backlog,title:'Persisted'},backlog);
await deleteAgenda('schedule_entries', state.scheduleEntries.find(e=>e.id===entry.id)); assert.equal(state.timeLogs.length,0);
state.mode='signed_out'; await assert.rejects(()=>saveEntry({title:'Denied',category:'work'}));
console.log('PASS: agenda week boundaries, night split, cross-week actual intervals, editing, overlap guard, goals, backlog, seed idempotency, DST, atomic shift validation, persistence, cascade and signed-out protection.');
