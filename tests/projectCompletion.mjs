import './datiDiProva.mjs';
import assert from 'node:assert/strict';
import {state} from '../dist/js/services/store.js?v=65';
globalThis.document={querySelector:()=>({addEventListener(){}})};
const {filteredTasks, filters, taskTable, filterBar}=await import('../dist/js/modules/tasks.js?v=65');
import {setTaskStatus} from '../dist/js/services/dataService.js?v=65';
import {progress} from '../dist/js/utils/helpers.js?v=65';
const storage=new Map([['cm-local-demo','yes']]);
globalThis.localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)};
state.mode='demo';
const project=state.projects[0];
Object.assign(filters,{project:'',status:'',priority:'',type:'',due:'',tag:'',sort:'due'});
const task=filteredTasks(project.id)[0];
const initialCount=filteredTasks(project.id).length;
assert(task && task.status!=='completed');
assert.match(taskTable([task],{completion:true}),/type="checkbox"/);
assert(!taskTable([task]).includes('type="checkbox"'));
assert.match(filterBar(project.id),/Da eseguire/);
await setTaskStatus(task.id,'completed');
assert.equal(filteredTasks(project.id).length,initialCount-1);
assert(!filteredTasks(project.id).some(t=>t.id===task.id));
assert(filteredTasks().some(t=>t.id===task.id));
assert(state.tasks.find(t=>t.id===task.id).completed_at);
filters.status='completed';
assert(filteredTasks(project.id).some(t=>t.id===task.id));
assert.match(taskTable(filteredTasks(project.id),{completion:true}),/checked/);
filters.status='all';assert(filteredTasks(project.id).some(t=>t.id===task.id));
const completedProgress=progress(state.tasks.filter(t=>t.project_id===project.id));

await setTaskStatus(task.id,'todo');filters.status='';
assert.equal(filteredTasks(project.id).length,initialCount);
assert(progress(state.tasks.filter(t=>t.project_id===project.id))<completedProgress);
state.mode='signed_out';await assert.rejects(()=>setTaskStatus(task.id,'completed'));
assert.equal(state.tasks.find(t=>t.id===task.id).status,'todo');
console.log('PASS: project completion hides task, preserves history and persisted status, updates progress, allows reopening; denied save keeps task open.');
