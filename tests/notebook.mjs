import { saveNote } from '../dist/js/services/notesService.js?v=65';
import { noteLinks } from '../dist/js/utils/noteLinks.js?v=65';
import assert from 'node:assert/strict';
import { state } from '../dist/js/services/store.js?v=65';
import { saveDailyTodo } from '../dist/js/services/notebookService.js?v=65';
const storage=new Map();
globalThis.localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)};
state.mode='demo';state.dailyTodos=[];
let item=await saveDailyTodo({title:'Daily test',todo_date:'2026-09-14'});
item=await saveDailyTodo({...item,todo_date:'2026-09-15',is_completed:true},item);
assert.equal(state.dailyTodos.length,1);assert.equal(item.is_completed,true);
await assert.rejects(()=>saveDailyTodo({title:'Invalid',todo_date:'2026-02-30'}));
state.mode='signed_out';await assert.rejects(()=>saveDailyTodo({title:'Denied'}));
console.log('PASS: notebook dates, editing, completion and signed-out guard.');

state.mode='demo';state.notes=[];
const note=await saveNote({title:'Reference',body:'https://example.com'});
await saveNote({title:'Updated reference',body:'Plain text'},note);
assert.equal(state.notes.length,1);assert.equal(state.notes[0].title,'Updated reference');
assert.match(noteLinks('https://example.com'),/rel="noopener noreferrer"/);
assert(!noteLinks('<script>alert(1)</script> javascript:alert(1)').includes('<script>'));
assert(!noteLinks('javascript:alert(1)').includes('href='));
console.log('PASS: notes create/edit and safe link rendering.');

state.mode='demo';
let undated=await saveDailyTodo({title:'No date'});
assert.equal(undated.todo_date,null);
assert.equal(state.dailyTodos.at(-1).todo_date,null);
undated=await saveDailyTodo({...undated,todo_date:'2026-10-01'},undated);
assert.equal(undated.todo_date,'2026-10-01');
undated=await saveDailyTodo({...undated,todo_date:'',is_completed:true},undated);
assert.equal(undated.todo_date,null);
assert.equal(undated.is_completed,true);
globalThis.window={addEventListener(){}};
globalThis.document={querySelector:()=>({addEventListener(){}})};
const {notebookPage}=await import('../dist/js/modules/notebook.js?v=65');
const html=notebookPage('daily-todos');
assert.ok(html.includes('No date') && html.includes('Daily test'));
assert.ok(html.includes('name="todo_date" value=""'));
assert.ok(!html.includes('id="notebook-date"'));
console.log('PASS: undated creation, adding/removing date, completion, all-date list.');
