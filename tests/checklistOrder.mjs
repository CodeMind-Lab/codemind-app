import assert from 'node:assert/strict';
import {state} from '../dist/js/services/store.js?v=65';
import {tableRows, tableDefaults, compareChecklistTasks} from '../dist/js/utils/checklist.js?v=65';
globalThis.document={querySelector:()=>({addEventListener(){}})};
const {filteredTasks,filters,filterBar}=await import('../dist/js/modules/tasks.js?v=65');
state.projects=[{id:'project',name:'Progetto',status:'active'}];
const make=(id,position,description='')=>({id,project_id:'project',title:id,position,description,status:'todo',priority:'medium',tags:[]});
state.tasks=[make('uuid-a',2),make('uuid-z',0),make('uuid-b',1)];
assert.deepEqual(filteredTasks('project').map(t=>t.id),['uuid-z','uuid-b','uuid-a']);
assert.match(filterBar('project'),/value="id" selected/);
const grid=[['ID','Attività'],['DLD-10','Dieci'],['DLD-2','Due'],['DLD-1','Uno']];
const rows=tableRows(grid,tableDefaults(grid));
state.tasks=rows.map((row,i)=>({...make(`uuid-${i}`,i),...row}));
assert.deepEqual(filteredTasks('project').map(t=>t.title),['Uno','Due','Dieci']);
state.tasks.find(t=>t.title==='Due').status='completed';
assert.deepEqual(filteredTasks('project').map(t=>t.title),['Uno','Dieci']);
filters.status='all';assert.deepEqual(filteredTasks('project').map(t=>t.title),['Uno','Due','Dieci']);
filters.sort='due';state.tasks[0].due_date='2026-10-05';
assert.equal(filteredTasks('project')[0].title,'Dieci');
filters.sort='';assert.equal(filteredTasks('project')[0].title,'Uno');
const mixed=[make('no-id',0),make('id-10',1,'ID: 10'),make('id-2',2,'ID: 2')];
assert.deepEqual(mixed.sort(compareChecklistTasks).map(t=>t.id),['id-2','id-10','no-id']);
const noHeaders=[['DLD-010','Dieci','Altro titolo'],['DLD-002','Due','Secondo']];
const mapped=tableRows(noHeaders,{column:1,idColumn:0,hasHeader:false});
assert.equal(mapped[0].sourceId,'DLD-010');
assert.equal(mapped[1].description,'ID: DLD-002');
mapped[0].title='Titolo modificato';
assert.equal(mapped[0].sourceId,'DLD-010');
assert.deepEqual(mapped.sort(compareChecklistTasks).map(r=>r.sourceId),['DLD-002','DLD-010']);
assert.equal(tableRows(noHeaders,{column:2,idColumn:0})[0].sourceId,'DLD-010');
assert.equal(tableRows(noHeaders,{column:1,idColumn:-1})[0].sourceId,undefined);
console.log('PASS: existing checklist row order, natural source ID order, project default, completion filters, explicit sorts and mixed records.');
